import test from 'node:test';
import assert from 'node:assert/strict';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
const temp=fs.mkdtempSync(path.join(os.tmpdir(),'scope-management-'));
process.env.NIMBUS_CONFIG=path.join(temp,'config.json');
const initial={mcpServers:{synthetic:{command:'not-launched',env:{SECRET:'sentinel'},scope:{allow:{workerIds:[22]}}}},unrelated:{keep:true}};
fs.writeFileSync(process.env.NIMBUS_CONFIG,JSON.stringify(initial));
const {execute}=await import('../runtime/toolsets/generated/mcp_connector_scope.js');
const ctx={bot:{tools:'["mcp_connector_scope"]'}};
const call=args=>execute('mcp_connector_scope',args,ctx);
test.after(()=>fs.rmSync(temp,{recursive:true,force:true}));
test('management status, offline validation, CAS, exact replacement and reread',()=>{
 const before=fs.readFileSync(process.env.NIMBUS_CONFIG,'utf8');
 const status=call({action:'status',server:'synthetic'});
 assert.equal(status.supported,true);assert.equal(status.policyVersion,1);
 assert.ok(!JSON.stringify(status).includes('sentinel'));
 const scope={allow:{templates:['orchestrator']}};
 assert.equal(call({action:'validate',server:'synthetic',scope}).valid,true);
 assert.equal(fs.readFileSync(process.env.NIMBUS_CONFIG,'utf8'),before);
 assert.throws(()=>call({action:'validate',server:'synthetic',scope,expectedPolicyHash:status.policyHash}),/does not accept/);
 assert.throws(()=>call({action:'set',server:'synthetic',scope,expectedPolicyHash:'0'.repeat(64)}),/policy_conflict/);
 assert.equal(fs.readFileSync(process.env.NIMBUS_CONFIG,'utf8'),before);
 const saved=call({action:'set',server:'synthetic',scope,expectedPolicyHash:status.policyHash});
 assert.equal(saved.saved,true);assert.deepEqual(saved.scope,scope);
 const current=JSON.parse(fs.readFileSync(process.env.NIMBUS_CONFIG,'utf8'));
 assert.deepEqual(current.mcpServers.synthetic.scope,scope);
 assert.equal(current.mcpServers.synthetic.env.SECRET,'sentinel');assert.deepEqual(current.unrelated,{keep:true});
 assert.equal(call({action:'status'}).policyHash,saved.policyHash);
});
